import AppKit
import Foundation
import MacrophoneKit

/// The clipboard, both ways, only when the phone asks (Oct 18 2026): the Mac's text or image goes
/// to the phone; the phone's goes onto the Mac's clipboard, to paste with ⌘V. A copy a password
/// manager marks as concealed or transient never leaves the Mac. What's on it is never logged.
enum ClipboardShare {
    /// The marks password managers put on what they copy (nspasteboard.org).
    private static let privateTypes: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                                                    "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"]

    static func read() -> (ClipboardItem?, String) {
        let pb = NSPasteboard.general
        let types = Set((pb.types ?? []).map(\.rawValue))
        if !types.isDisjoint(with: privateTypes) {
            return (nil, "Your Mac's clipboard holds something private — it stays on your Mac")
        }
        if let text = pb.string(forType: .string), !text.isEmpty {
            let cut = text.utf8.count > ClipboardItem.maxText
            let t = cut ? String(decoding: Data(text.utf8).prefix(ClipboardItem.maxText), as: UTF8.self) : text
            return (ClipboardItem(text: t), cut ? "Copied the start of your Mac's clipboard — it's long" : "Copied from your Mac")
        }
        if let image = NSImage(pasteboard: pb), let data = shrink(image) {
            return (ClipboardItem(image: data), "Copied the image from your Mac")
        }
        return (nil, "Your Mac's clipboard is empty")
    }

    static func write(_ item: ClipboardItem) -> String {
        let pb = NSPasteboard.general
        if let text = item.text, !text.isEmpty {
            pb.clearContents()
            pb.setString(text, forType: .string)
            return "On your Mac's clipboard — press ⌘V to paste"
        }
        if let data = item.image, let image = NSImage(data: data) {
            pb.clearContents()
            pb.writeObjects([image])
            return "The image is on your Mac's clipboard — press ⌘V to paste"
        }
        return "Nothing to send — your iPhone's clipboard is empty"
    }

    /// An image small enough for the clipboard: PNG when it fits, else JPEG, else smaller.
    private static func shrink(_ image: NSImage) -> Data? {
        guard var rep = image.representations.compactMap({ $0 as? NSBitmapImageRep }).first
                ?? image.tiffRepresentation.flatMap(NSBitmapImageRep.init(data:)) else { return nil }
        if let png = rep.representation(using: .png, properties: [:]), png.count <= ClipboardItem.maxImage { return png }
        for side in [2400.0, 1600.0, 1100.0] {
            let w = Double(rep.pixelsWide), h = Double(rep.pixelsHigh)
            let k = min(1, side / max(w, h))
            if k < 1, let scaled = scale(rep, k) { rep = scaled }
            if let jpg = rep.representation(using: .jpeg, properties: [.compressionFactor: 0.8]), jpg.count <= ClipboardItem.maxImage { return jpg }
        }
        return nil
    }

    private static func scale(_ rep: NSBitmapImageRep, _ k: Double) -> NSBitmapImageRep? {
        let w = Int(Double(rep.pixelsWide) * k), h = Int(Double(rep.pixelsHigh) * k)
        guard let out = NSBitmapImageRep(bitmapDataPlanes: nil, pixelsWide: w, pixelsHigh: h, bitsPerSample: 8, samplesPerPixel: 4,
                                         hasAlpha: true, isPlanar: false, colorSpaceName: .deviceRGB, bytesPerRow: 0, bitsPerPixel: 0)
        else { return nil }
        NSGraphicsContext.saveGraphicsState()
        NSGraphicsContext.current = NSGraphicsContext(bitmapImageRep: out)
        rep.draw(in: NSRect(x: 0, y: 0, width: w, height: h))
        NSGraphicsContext.restoreGraphicsState()
        return out
    }
}
